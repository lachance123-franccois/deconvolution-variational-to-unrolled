function [net, tinfo] = train_cnn1d(Xin, Xout, Xin_val, Xout_val, opts)
N = size(Xin, 1);
depth  = opt_get(opts, 'depth', 12);
nf     = opt_get(opts, 'filters', 32);
fsize  = opt_get(opts, 'fsize', 5);
epochs = opt_get(opts, 'epochs', 30);
bs     = opt_get(opts, 'batch', 64);
lr     = opt_get(opts, 'lr', 1e-3);

to4d = @(A) reshape(A, N, 1, 1, []);
lgraph = build_cnn1d(N, depth, nf, fsize);
options = trainingOptions('adam', ...
    'MaxEpochs', epochs, ...
    'MiniBatchSize', bs, ...
    'InitialLearnRate', lr, ...
    'LearnRateSchedule', 'piecewise', ...
    'LearnRateDropPeriod', max(1, round(epochs / 3)), ...
    'LearnRateDropFactor', 0.3, ...
    'Shuffle', 'every-epoch', ...
    'ValidationData', {to4d(Xin_val), to4d(Xout_val)}, ...
    'ValidationFrequency', 100, ...
    'Verbose', true, ...
    'VerboseFrequency', 200, ...
    'Plots', 'none');
[net, tinfo] = trainNetwork(to4d(Xin), to4d(Xout), lgraph, options);
end
